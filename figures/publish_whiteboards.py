"""Copy the accepted whiteboard sheets from figures/ into docs/whiteboards/ for GitHub Pages.

figures/ is the workshop: prompts, attempts, reviews, and the accepted sheets as PNG. docs/whiteboards/
holds only what a reader needs: each accepted sheet as JPEG, one PDF per set, and an index page.
Everything under docs/whiteboards/ is generated by this script; do not edit it by hand.

    python3 figures/publish_whiteboards.py

Run it again after a sheet is redrawn or a set is added. It rewrites docs/whiteboards/ from scratch.
"""
