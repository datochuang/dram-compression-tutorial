def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    cards, nav = [], []
    for folder, title, desc, names in SETS:
        d = OUT / folder
        d.mkdir()
        jpgs, ims = [], []
        for f in sheets(folder, names):
            im = Image.open(f).convert('RGB')
            j = d / f'{f.stem}.jpg'
            im.save(j, quality=QUALITY, optimize=True, progressive=True)
            jpgs.append(j)
            ims.append(Image.open(j).convert('RGB'))
        pdf = d / f'{folder}.pdf'
        ims[0].save(pdf, save_all=True, append_images=ims[1:], resolution=150, quality=QUALITY)
        cards.append(card(folder, title, desc, jpgs, pdf))
        nav.append(f'      <a href="#{folder}">{html.escape(title)}</a>')
        print(f'{folder}: {len(jpgs)} sheets, pdf {pdf.stat().st_size // 1024} KB')
    (OUT / 'index.html').write_text(PAGE.format(nav='\n'.join(nav), cards='\n'.join(cards)))
    total = sum(p.stat().st_size for p in OUT.rglob('*') if p.is_file())
    print(f'docs/whiteboards: {total / 1e6:.1f} MB')


if __name__ == '__main__':
    main()
